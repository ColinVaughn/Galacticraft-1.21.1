package dev.galacticraft.mod.client.gui.screen.ingame.jupiter;

import dev.galacticraft.machinelib.api.block.entity.MachineBlockEntity;
import dev.galacticraft.machinelib.api.machine.MachineStatus;
import dev.galacticraft.machinelib.client.api.screen.MachineScreen;
import dev.galacticraft.mod.Constant;
import dev.galacticraft.mod.screen.jupiter.JupiterMachineMenu;
import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
import net.minecraft.client.gui.GuiGraphics;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.FormattedCharSequence;
import net.minecraft.world.entity.player.Inventory;
import org.jetbrains.annotations.NotNull;

import java.util.ArrayList;
import java.util.List;

/**
 * Shared Jupiter machine screen helpers. Gauge and lamp sprites are generated by
 * {@code tools/jupiter_gui_textures.py} below the main panel.
 */
@Environment(EnvType.CLIENT)
public abstract class JupiterMachineScreen<T extends MachineBlockEntity> extends MachineScreen<T, JupiterMachineMenu<T>> {
    public static final int TEXT = 0xFF404040, ASIDE = 0xFF707070, FAULT = 0xFFAA0000, GOOD = 0xFF00AA00;
    private static final int LINE = 10;
    private static final int FILL_V = 168, FILL_STEP = 7, FILL_WIDTH = 160, GAUGE_HEIGHT = 6;
    private static final int LAMP_V = 204, LAMP_SIZE = 9;

    /** Gauge fills, in the order the texture tool paints them. */
    public enum Fill { AMBER, BLUE, RED, CYAN, GREEN }

    /** Lamps, in the order the texture tool paints them. */
    public enum Lamp { OFF, RED, AMBER, GREEN }

    private record Tip(int x, int y, int width, int height, List<Component> lines) { }

    private final List<Tip> tips = new ArrayList<>();
    /** MachineScreen keeps its own copy private; the gauges and lamps draw from the same file. */
    private final ResourceLocation sprites;
    /** Left edge of the strip the title is centred in; everything left of it starts higher up. */
    protected int titleStart = 28;

    protected JupiterMachineScreen(JupiterMachineMenu<T> menu, Inventory inventory, Component title, String id) {
        super(menu, title, texture(id));
        this.sprites = texture(id);
    }

    public static ResourceLocation texture(String id) {
        return Constant.id("textures/gui/jupiter/" + id + ".png");
    }

    @Override
    protected void drawTitle(@NotNull GuiGraphics graphics) {
        int width = this.font.width(this.title);
        int x = this.titleStart + Math.max(0, (this.imageWidth - 4 - this.titleStart - width) / 2);
        graphics.drawString(this.font, this.title, x, 6, TEXT, false);
    }

    @Override
    protected void renderMachineBackground(GuiGraphics graphics, int mouseX, int mouseY, float delta) {
        super.renderMachineBackground(graphics, mouseX, mouseY, delta);
        this.tips.clear();
        this.drawReadout(graphics, this.leftPos, this.topPos);
    }

    /** Draws the machine's readout; {@code x} and {@code y} are the screen's top-left corner. */
    protected abstract void drawReadout(GuiGraphics graphics, int x, int y);

    @Override
    protected void renderTooltip(GuiGraphics graphics, int mouseX, int mouseY) {
        super.renderTooltip(graphics, mouseX, mouseY);
        if (this.hoveredSlot != null && this.hoveredSlot.hasItem()) return;
        for (Tip tip : this.tips) {
            int x = this.leftPos + tip.x(), y = this.topPos + tip.y();
            if (mouseX >= x && mouseX < x + tip.width() && mouseY >= y && mouseY < y + tip.height()) {
                graphics.renderComponentTooltip(this.font, tip.lines(), mouseX, mouseY);
                return;
            }
        }
    }

    protected int value(int index) {
        return this.menu.value(index);
    }

    protected boolean working() {
        MachineStatus status = this.menu.state.getStatus();
        return status != null && status.getType().isActive();
    }

    /** One line of panel text at panel-relative {@code (x, y)}, in the classic dark grey. */
    protected void text(GuiGraphics graphics, Component text, int x, int y) {
        this.text(graphics, text, x, y, TEXT);
    }

    protected void text(GuiGraphics graphics, Component text, int x, int y, int color) {
        graphics.drawString(this.font, text, this.leftPos + x, this.topPos + y, color, false);
    }

    /** Panel text cut down to {@code width}, for names that come from players. */
    protected void clipped(GuiGraphics graphics, String text, int x, int y, int width, int color) {
        this.text(graphics, Component.literal(this.font.plainSubstrByWidth(text, width)), x, y, color);
    }

    protected void textRight(GuiGraphics graphics, Component text, int right, int y, int color) {
        this.text(graphics, text, right - this.font.width(text), y, color);
    }

    /** Wrapped text inside a {@code width}-wide column; returns the y after the last line drawn. */
    protected int wrapped(GuiGraphics graphics, Component text, int x, int y, int width, int maxLines, int color) {
        List<FormattedCharSequence> lines = this.font.split(text, width);
        for (int i = 0; i < Math.min(maxLines, lines.size()); i++) {
            graphics.drawString(this.font, lines.get(i), this.leftPos + x, this.topPos + y, color, false);
            y += LINE;
        }
        return y;
    }

    /**
     * Draws a status lamp and dark text for contrast against the light panel.
     */
    protected void status(GuiGraphics graphics, int x, int y, int width) {
        MachineStatus status = this.menu.state.getStatus();
        if (status == null) return;
        this.lamp(graphics, x, y - 1, statusLamp(status));
        this.statusText(graphics, x + 13, y, width - 13);
    }

    /** Just the status text, for screens whose own lamp already shows the state. */
    protected void statusText(GuiGraphics graphics, int x, int y, int width) {
        MachineStatus status = this.menu.state.getStatus();
        if (status != null) this.clipped(graphics, status.getText().getString(), x, y, width, TEXT);
    }

    private static Lamp statusLamp(MachineStatus status) {
        return switch (status.getType()) {
            case WORKING -> Lamp.GREEN;
            case PARTIALLY_WORKING -> Lamp.AMBER;
            case OTHER -> Lamp.OFF;
            default -> Lamp.RED;
        };
    }

    /** Fills a gauge the texture recesses at panel-relative {@code (x, y)}, {@code width} wide. */
    protected void gauge(GuiGraphics graphics, int x, int y, int width, float fraction, Fill fill) {
        int filled = Math.round(Math.min(width, FILL_WIDTH) * Math.max(0, Math.min(1, fraction)));
        if (filled > 0) {
            graphics.blit(this.sprites, this.leftPos + x, this.topPos + y, 0, FILL_V + fill.ordinal() * FILL_STEP, filled, GAUGE_HEIGHT);
        }
    }

    protected void lamp(GuiGraphics graphics, int x, int y, Lamp lamp) {
        graphics.blit(this.sprites, this.leftPos + x, this.topPos + y, lamp.ordinal() * LAMP_SIZE, LAMP_V, LAMP_SIZE, LAMP_SIZE);
    }

    /** Shows {@code lines} while the mouse is over the panel-relative area; register it while drawing the readout. */
    protected void tooltip(int x, int y, int width, int height, Component... lines) {
        this.tips.add(new Tip(x, y, width, height, List.of(lines)));
    }
}
